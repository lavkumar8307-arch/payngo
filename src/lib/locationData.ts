// Local Indexed Search Engine with Prefix Matching, Aliases, State Ranking & Popularity
export function searchLocationsLocal(query: string, limit: number = 10): LocationItem[] {
  const normQ = normalizeText(query);
  if (!normQ) {
    return COMPREHENSIVE_INDIAN_LOCATIONS.slice(0, limit);
  }

  const matches: { item: LocationItem; score: number }[] = [];

  for (const item of COMPREHENSIVE_INDIAN_LOCATIONS) {
    let score = 0;
    const normName = item.normalizedName;
    const normState = normalizeText(item.state);

    // Exact name match
    if (normName === normQ) {
      score += 100;
    }
    // Prefix name match
    else if (normName.startsWith(normQ)) {
      score += 80;
    }
    // Substring name match
    else if (normName.includes(normQ)) {
      score += 60;
    }

    // Alias matches
    for (const alias of item.aliases) {
      const normAlias = normalizeText(alias);
      if (normAlias === normQ) {
        score += 90;
      } else if (normAlias.startsWith(normQ)) {
        score += 70;
      } else if (normAlias.includes(normQ)) {
        score += 50;
      }
    }

    // State name match
    if (normState.startsWith(normQ)) {
      score += 65;
    } else if (normState.includes(normQ)) {
      score += 45;
    }

    if (score > 0) {
      // Add popularity weighting (0.1 multiplier)
      score += item.popularity * 0.1;
      matches.push({ item, score });
    }
  }

  // Sort descending by score
  matches.sort((a, b) => b.score - a.score);

  return matches.slice(0, limit).map((m) => m.item);
}

